#!/usr/bin/env bash
# Copy the rules controller-gen rendered into config/rbac/role.yaml into the Helm chart's ClusterRole, so
# the markers in internal/rbac/doc.go stay the single source of truth. Run by `make manifests`.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/config/rbac/role.yaml"
DST="$ROOT/charts/kubevirt-drs/templates/controller/clusterrole.yaml"
[[ -f "$SRC" ]] || { echo "missing $SRC: run make manifests first" >&2; exit 1; }
{
  cat <<'HDR'
{{- /* GENERATED by hack/sync-rbac.sh from config/rbac/role.yaml (markers: internal/rbac/doc.go). Do not edit. */ -}}
{{- if .Values.controller.enabled }}
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: {{ include "kubevirt-drs.fullname" . }}-manager
  labels:
    {{- include "kubevirt-drs.labels" . | nindent 4 }}
HDR
  sed -n '/^rules:/,$p' "$SRC"
  echo '{{- end }}'
} > "$DST"
echo "synced $DST"
